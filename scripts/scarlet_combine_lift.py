#!/usr/bin/env python3
"""Combine per-module Scarlet lift output into one native-code source tree.

The generated guest function names contain absolute guest addresses, so main,
sdk and subsdk0 can coexist in one DLL. This stage combines function sources,
prototypes, the indirect-call table and EH landing-pad resume table. Import
metadata is intentionally not faked here: the multi-module loader owns ELF
relocations and external symbol binding.
"""
import argparse
import json
import os
import re
import shutil
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(REPO, "scripts"))
import scarlet_profile as profile  # noqa: E402

FN_RE = re.compile(r"\{\s*(0x[0-9a-fA-F]+)ULL,\s*(f_[0-9a-fA-F]+)\s*\},")
RESUME_RE = re.compile(r"\{\s*(0x[0-9a-fA-F]+)ULL,\s*(u_[0-9a-fA-F]+)\s*\},")
DECL_RE = re.compile(r"^void\s+[fu]_[0-9a-fA-F]+\(Ctx \*c(?:, uint64_t rp)?\);$")


def write_if_changed(path, data):
    old = None
    try:
        with open(path, "rb") as f:
            old = f.read()
    except OSError:
        pass
    raw = data.encode("utf-8")
    if old == raw:
        return False
    with open(path, "wb") as f:
        f.write(raw)
    return True


def copy_if_changed(src, dst):
    try:
        if os.path.getsize(src) == os.path.getsize(dst):
            with open(src, "rb") as a, open(dst, "rb") as b:
                if a.read() == b.read():
                    return False
    except OSError:
        pass
    shutil.copy2(src, dst)
    return True


def parse_module(path):
    funcs = []
    resume = []
    decls = set()
    with open(os.path.join(path, "table.c"), encoding="latin-1") as f:
        table = f.read()
    funcs = [(int(a, 16), fn) for a, fn in FN_RE.findall(table)]
    resume = [(int(a, 16), fn) for a, fn in RESUME_RE.findall(table)]
    with open(os.path.join(path, "funcs.h"), encoding="latin-1") as f:
        for line in f:
            line = line.strip()
            if DECL_RE.match(line):
                decls.add(line)
    sources = sorted(n for n in os.listdir(path)
                     if n.startswith("c_") and n.endswith(".c"))
    return funcs, resume, decls, sources


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--lift", default=os.path.join(REPO, "build", "lift"))
    ap.add_argument("--out", default=os.path.join(REPO, "build", "lift_combined"))
    ap.add_argument("--module-map", default=os.path.join(REPO, "build", "scarlet_module_map.json"))
    a = ap.parse_args(argv)

    lift = os.path.abspath(a.lift)
    out = os.path.abspath(a.out)
    os.makedirs(out, exist_ok=True)

    all_funcs = []
    all_resume = []
    all_decls = set()
    keep = {"funcs.h", "table.c", "imports.c", "scarlet_combined_manifest.json"}
    module_stats = {}
    copied = changed = 0

    for module in profile.STATIC_MODULES:
        srcdir = os.path.join(lift, module)
        if not os.path.isdir(srcdir):
            raise FileNotFoundError(srcdir)
        funcs, resume, decls, sources = parse_module(srcdir)
        all_funcs.extend((addr, fn, module) for addr, fn in funcs)
        all_resume.extend((addr, fn, module) for addr, fn in resume)
        all_decls.update(decls)
        module_stats[module] = {
            "functions": len(funcs),
            "resume_entries": len(resume),
            "sources": len(sources),
        }
        for name in sources:
            dst_name = "%s_%s" % (module, name)
            keep.add(dst_name)
            copied += 1
            if copy_if_changed(os.path.join(srcdir, name), os.path.join(out, dst_name)):
                changed += 1

    # Absolute guest addresses make duplicates a correctness error.
    by_addr = {}
    for addr, fn, module in all_funcs:
        if addr in by_addr and by_addr[addr][0] != fn:
            raise RuntimeError("function address collision %#x: %s / %s" %
                               (addr, by_addr[addr], (fn, module)))
        by_addr[addr] = (fn, module)
    all_funcs = [(addr, fn, module) for addr, (fn, module) in sorted(by_addr.items())]

    # A landing pad address must point at only one wrapper.
    by_pad = {}
    for addr, fn, module in all_resume:
        old = by_pad.get(addr)
        if old and old[0] != fn:
            raise RuntimeError("EH resume collision %#x: %s / %s" %
                               (addr, old, (fn, module)))
        by_pad[addr] = (fn, module)
    all_resume = [(addr, fn, module) for addr, (fn, module) in sorted(by_pad.items())]

    funcs_h = [
        "/* generated by scarlet_combine_lift.py -- do not edit */",
        "#pragma once",
        "void nro_catch_call(Ctx *c, void (*body)(Ctx *, uint64_t));",
    ]
    funcs_h.extend(sorted(all_decls))
    funcs_h.append("")
    write_if_changed(os.path.join(out, "funcs.h"), "\n".join(funcs_h))

    table = [
        "/* generated by scarlet_combine_lift.py -- do not edit */",
        '#include "runtime.h"',
        '#include "funcs.h"',
        "",
        "const FnEntry fn_table[] = {",
    ]
    table.extend("  { 0x%xULL, %s }," % (addr, fn) for addr, fn, _ in all_funcs)
    table += [
        "};",
        "const int fn_table_count = %d;" % len(all_funcs),
        "",
        "typedef struct { uint64_t lp; void (*fn)(Ctx *, uint64_t); } NroResume;",
        "const NroResume resume_table_main[] = {",
    ]
    table.extend("  { 0x%xULL, %s }," % (addr, fn) for addr, fn, _ in all_resume)
    table += [
        "  { 0, 0 }",
        "};",
        "const int resume_count_main = %d;" % len(all_resume),
        "",
    ]
    write_if_changed(os.path.join(out, "table.c"), "\n".join(table))

    # hostrt.c's import/HLE accounting remains keyed to main's original dynsym
    # indices. sdk/subsdk0 relocations are handled by the Scarlet module loader,
    # so do not concatenate their dynsym arrays and silently change indices.
    main_imports = os.path.join(lift, "main", "imports.c")
    if not os.path.isfile(main_imports):
        raise FileNotFoundError(main_imports)
    copy_if_changed(main_imports, os.path.join(out, "imports.c"))

    unresolved = {}
    weak_unresolved = {}
    strong_unresolved = {}
    ordered = {}
    if os.path.isfile(a.module_map):
        with open(a.module_map, encoding="utf-8") as f:
            mm = json.load(f)
        unresolved = mm.get("unresolved", {})
        weak_unresolved = mm.get("weak_unresolved", {})
        strong_unresolved = mm.get("strong_unresolved", {})
        for module, resolutions in mm.get("resolutions", {}).items():
            ordered[module] = {
                name: target for name, target in resolutions.items()
                if target.get("resolution") == "module-load-order"
            }

    manifest = {
        "format": 1,
        "game": profile.GAME_NAME,
        "version": profile.BASE_VERSION,
        "modules": module_stats,
        "source_files": copied,
        "functions": len(all_funcs),
        "resume_entries": len(all_resume),
        "external_imports_pending_loader": unresolved,
        "weak_unresolved_imports": weak_unresolved,
        "strong_unresolved_imports": strong_unresolved,
        "load_order_resolutions": ordered,
        "dyn_syms": "main-only; sdk/subsdk0 relocations are loader-owned",
        "runtime_ready": False,
        "runtime_blocker": "multi-module ELF relocation loader not integrated yet",
    }
    write_if_changed(
        os.path.join(out, "scarlet_combined_manifest.json"),
        json.dumps(manifest, indent=2, sort_keys=True) + "\n",
    )

    for name in os.listdir(out):
        if name not in keep and ((name.endswith(".c") and "_c_" in name) or
                                 name in ("funcs.h", "table.c", "scarlet_combined_manifest.json")):
            os.remove(os.path.join(out, name))

    print("Scarlet combined lift")
    for module in profile.STATIC_MODULES:
        st = module_stats[module]
        print("  %-7s sources=%4d functions=%6d resume=%5d" %
              (module, st["sources"], st["functions"], st["resume_entries"]))
    print("  combined sources: %d (%d copied/updated)" % (copied, changed))
    print("  combined functions: %d" % len(all_funcs))
    print("  combined EH resume entries: %d" % len(all_resume))
    print("  output: %s" % out)
    strong_total = sum(len(v) for v in strong_unresolved.values()) if strong_unresolved else 0
    weak_total = sum(len(v) for v in weak_unresolved.values()) if weak_unresolved else 0
    print("  unresolved imports: strong=%d weak=%d" % (strong_total, weak_total))
    print("  runtime-ready: NO (multi-module ELF relocation loader is the next stage)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
