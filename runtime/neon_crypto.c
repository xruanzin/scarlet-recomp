static uint8_t aes_xtime(uint8_t x) {
    return (uint8_t)((x << 1) ^ ((x & 0x80) ? 0x1b : 0));
}
static uint8_t aes_mul(uint8_t x, uint8_t y) {
    uint8_t r = 0;
    while (y) {
        if (y & 1) r ^= x;
        x = aes_xtime(x);
        y >>= 1;
    }
    return r;
}

void v_crypto_aese(V128 *d, const V128 *key, int decrypt) {
    V128 in = *d, k = *key, r;
    uint8_t x[16];
    for (int i = 0; i < 16; i++) x[i] = in.b[i] ^ k.b[i];
    for (int c = 0; c < 4; c++) {
        for (int row = 0; row < 4; row++) {
            int src_col = decrypt ? (c - row + 4) & 3 : (c + row) & 3;
            uint8_t v = x[4 * src_col + row];
            r.b[4 * c + row] = decrypt ? aes_isbox[v] : aes_sbox[v];
        }
    }
    *d = r;
}

void v_crypto_aesmc(V128 *d, const V128 *src, int inverse) {
    V128 a = *src, r;
    for (int c = 0; c < 4; c++) {
        uint8_t x0=a.b[4*c], x1=a.b[4*c+1], x2=a.b[4*c+2], x3=a.b[4*c+3];
        if (!inverse) {
            r.b[4*c]   = aes_mul(x0,2) ^ aes_mul(x1,3) ^ x2 ^ x3;
            r.b[4*c+1] = x0 ^ aes_mul(x1,2) ^ aes_mul(x2,3) ^ x3;
            r.b[4*c+2] = x0 ^ x1 ^ aes_mul(x2,2) ^ aes_mul(x3,3);
            r.b[4*c+3] = aes_mul(x0,3) ^ x1 ^ x2 ^ aes_mul(x3,2);
        } else {
            r.b[4*c]   = aes_mul(x0,14)^aes_mul(x1,11)^aes_mul(x2,13)^aes_mul(x3,9);
            r.b[4*c+1] = aes_mul(x0,9)^aes_mul(x1,14)^aes_mul(x2,11)^aes_mul(x3,13);
            r.b[4*c+2] = aes_mul(x0,13)^aes_mul(x1,9)^aes_mul(x2,14)^aes_mul(x3,11);
            r.b[4*c+3] = aes_mul(x0,11)^aes_mul(x1,13)^aes_mul(x2,9)^aes_mul(x3,14);
        }
    }
    *d = r;
}

static uint32_t rol32c(uint32_t x, unsigned n) { return (x << n) | (x >> (32 - n)); }
static uint32_t ror32c(uint32_t x, unsigned n) { return (x >> n) | (x << (32 - n)); }
static uint32_t sha_ch(uint32_t x,uint32_t y,uint32_t z) { return (x & (y ^ z)) ^ z; }
static uint32_t sha_maj(uint32_t x,uint32_t y,uint32_t z) { return (x & y) | ((x | y) & z); }
static uint32_t sha_par(uint32_t x,uint32_t y,uint32_t z) { return x ^ y ^ z; }

void v_crypto_sha1_3(V128 *d, const V128 *n0, const V128 *m0, int kind) {
    V128 a=*d, n=*n0, m=*m0;
    for (int i=0;i<4;i++) {
        uint32_t f = kind==0 ? sha_ch(a.w[1],a.w[2],a.w[3])
                   : kind==1 ? sha_par(a.w[1],a.w[2],a.w[3])
                             : sha_maj(a.w[1],a.w[2],a.w[3]);
        uint32_t t = f + rol32c(a.w[0],5) + n.w[0] + m.w[i];
        n.w[0] = a.w[3];
        a.w[3] = a.w[2];
        a.w[2] = ror32c(a.w[1],2);
        a.w[1] = a.w[0];
        a.w[0] = t;
    }
    *d=a;
}
void v_crypto_sha1h(V128 *d, const V128 *n) {
    V128 r={{0}}; r.w[0]=ror32c(n->w[0],2); *d=r;
}
void v_crypto_sha1su0(V128 *d, const V128 *n, const V128 *m) {
    V128 a=*d, r;
    r.w[0]=a.w[2]^a.w[0]^m->w[0];
    r.w[1]=a.w[3]^a.w[1]^m->w[1];
    r.w[2]=n->w[0]^a.w[2]^m->w[2];
    r.w[3]=n->w[1]^a.w[3]^m->w[3];
    *d=r;
}
void v_crypto_sha1su1(V128 *d, const V128 *n) {
    V128 a=*d;
    a.w[0]=rol32c(a.w[0]^n->w[1],1);
    a.w[1]=rol32c(a.w[1]^n->w[2],1);
    a.w[2]=rol32c(a.w[2]^n->w[3],1);
    a.w[3]=rol32c(a.w[3]^a.w[0],1);
    *d=a;
}

static uint32_t S0_256(uint32_t x){return ror32c(x,2)^ror32c(x,13)^ror32c(x,22);}
static uint32_t S1_256(uint32_t x){return ror32c(x,6)^ror32c(x,11)^ror32c(x,25);}
static uint32_t s0_256(uint32_t x){return ror32c(x,7)^ror32c(x,18)^(x>>3);}
static uint32_t s1_256(uint32_t x){return ror32c(x,17)^ror32c(x,19)^(x>>10);}

void v_crypto_sha256h(V128 *d, const V128 *n0, const V128 *m0, int second) {
    V128 a=*d, n=*n0, m=*m0;
    if (!second) {
        for(int i=0;i<4;i++){
            uint32_t t=sha_ch(n.w[0],n.w[1],n.w[2])+n.w[3]+S1_256(n.w[0])+m.w[i];
            n.w[3]=n.w[2]; n.w[2]=n.w[1]; n.w[1]=n.w[0]; n.w[0]=a.w[3]+t;
            t+=sha_maj(a.w[0],a.w[1],a.w[2])+S0_256(a.w[0]);
            a.w[3]=a.w[2]; a.w[2]=a.w[1]; a.w[1]=a.w[0]; a.w[0]=t;
        }
    } else {
        for(int i=0;i<4;i++){
            uint32_t t=sha_ch(a.w[0],a.w[1],a.w[2])+a.w[3]+S1_256(a.w[0])+m.w[i];
            a.w[3]=a.w[2]; a.w[2]=a.w[1]; a.w[1]=a.w[0]; a.w[0]=n.w[3-i]+t;
        }
    }
    *d=a;
}
void v_crypto_sha256su0(V128 *d, const V128 *n) {
    V128 a=*d;
    a.w[0]+=s0_256(a.w[1]);
    a.w[1]+=s0_256(a.w[2]);
    a.w[2]+=s0_256(a.w[3]);
    a.w[3]+=s0_256(n->w[0]);
    *d=a;
}
void v_crypto_sha256su1(V128 *d, const V128 *n0, const V128 *m0) {
    V128 a=*d, n=*n0, m=*m0;
    a.w[0]+=s1_256(m.w[2])+n.w[1];
    a.w[1]+=s1_256(m.w[3])+n.w[2];
    a.w[2]+=s1_256(a.w[0])+n.w[3];
    a.w[3]+=s1_256(a.w[1])+m.w[0];
    *d=a;
}

void v_crypto_pmull64(V128 *d, const V128 *n, const V128 *m, int upper) {
    uint64_t a=n->d[upper?1:0], b=m->d[upper?1:0], lo=0, hi=0;
    for(int i=0;i<64;i++) if((b>>i)&1) {
        lo ^= a << i;
        if(i) hi ^= a >> (64-i);
    }
    d->d[0]=lo; d->d[1]=hi;
}
